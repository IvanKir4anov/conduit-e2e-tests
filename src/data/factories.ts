import { randomBytes } from 'node:crypto';
import { test } from '@playwright/test';
import type { NewArticle, NewUser } from '../api/types';

let counter = 0;

function workerIndex(): number {
  try {
    return test.info().workerIndex;
  } catch {
    return 0; // called outside a running test
  }
}

/**
 * Unique, URL-safe id: unique across parallel workers (worker index), across runs against
 * the same database (timestamp + random) and within one process (counter).
 */
export function uniqueId(prefix: string): string {
  counter += 1;
  const random = randomBytes(4).toString('hex').slice(0, 6);
  return `${prefix}-${workerIndex()}-${Date.now().toString(36)}${counter.toString(36)}-${random}`;
}

export function buildUser(overrides: Partial<NewUser> = {}): NewUser {
  const username = uniqueId('user');
  return {
    username,
    email: `${username}@example.test`,
    password: randomBytes(12).toString('base64url'),
    ...overrides,
  };
}

/**
 * The backend derives the slug from the title. Keep overridden titles short and unique:
 * a long common prefix could make slugs collide if the backend ever truncates them.
 */
export function buildArticle(overrides: Partial<NewArticle> = {}): NewArticle {
  return {
    title: `Article ${uniqueId('a')}`,
    description: 'Generated by an end-to-end test',
    body: `Body of the article ${uniqueId('body')}`,
    tagList: [uniqueId('tag')],
    ...overrides,
  };
}
